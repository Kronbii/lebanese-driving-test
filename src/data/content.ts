import { useSyncExternalStore } from "react";
import type { Lang, QuestionContent, TopicId } from "../domain/types";
import TOPIC_MAP from "./topic-map.json";

/**
 * Study content (explanations, why-wrong reasons, tips, translations) lives in
 * ./content/*.json, one file per id range. It is ~500 KB, so it loads in its own chunk
 * right after start-up instead of blocking the first screen. Accessors return undefined
 * until it has arrived; components re-render through useContentReady() (wired into the
 * settings context so every translated view refreshes).
 *
 * Topics are needed synchronously (exam building, stats), so they ship separately in
 * topic-map.json, generated by `npm run bank -- manifest`.
 *
 * Content is labelled as explanation in the UI and never replaces the official wording.
 */
const loaders = import.meta.glob<QuestionContent[]>("./content/*.json", { import: "default" });

export const CONTENT: Map<number, QuestionContent> = new Map();

let ready = false;
let loading: Promise<void> | null = null;
const listeners = new Set<() => void>();

export function loadContent(): Promise<void> {
  if (!loading) {
    loading = Promise.all(Object.values(loaders).map((load) => load()))
      .then((chunks) => {
        for (const chunk of chunks) for (const item of chunk) CONTENT.set(item.id, item);
        ready = true;
        listeners.forEach((listener) => listener());
      })
      .catch((error) => {
        loading = null;
        throw error;
      });
  }
  return loading;
}

export function isContentReady(): boolean {
  return ready;
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Starts loading the content and re-renders the caller once it is available. */
export function useContentReady(): boolean {
  if (!ready && !loading && typeof window !== "undefined") void loadContent().catch(() => undefined);
  return useSyncExternalStore(subscribe, isContentReady, isContentReady);
}

export function contentFor(id: number): QuestionContent | undefined {
  return CONTENT.get(id);
}

const TOPICS = TOPIC_MAP as Record<string, TopicId>;

export function topicOf(id: number): TopicId {
  return TOPICS[String(id)] ?? "traffic_rules";
}

export function explanationFor(id: number, lang: Lang): string | null {
  return CONTENT.get(id)?.explanation[lang] ?? null;
}

export function whyWrongFor(id: number, lang: Lang, option: number): string | null {
  return CONTENT.get(id)?.whyWrong[lang]?.[option] ?? null;
}

export function tipFor(id: number, lang: Lang): string | null {
  return CONTENT.get(id)?.tip?.[lang] ?? null;
}
